"""Вернуться к карточке SCALIA: кнопка меню и команда `/music`.

Карточка приходит один раз, в конце анкеты. Один раз — это правильно (второй
раз то же самое читается как реклама), но «один раз» без пути назад означает
«больше никогда»: человек, который в тот день торопился, не найдёт её уже
ничем.

Путей назад два, и они не дублируют друг друга, а закрывают разных людей.

- **Кнопка «🎧 Музыка SCALIA» в главном меню** — видимый вход. Её видно всем
  и всегда, искать не надо.
- **Команда `/music`** — для тех, кто говорит с ботом командами. В синем
  списке Telegram её нет, и это то же решение, что у `/referral`: список
  держится на десяти строках, и одиннадцатая вытеснила бы не «лишнюю».
  Команда при этом работает — просто её не видно, и до появления кнопки
  меню это и было её слабым местом.

Обе ведут в одно место — `services.music.отправить`. Второй сборки карточки
здесь нет и быть не должно: текст, кнопка и адрес живут в одном файле, и
разойтись им негде.
"""

from __future__ import annotations

from aiogram import F, Router
from aiogram.filters import Command
from aiogram.fsm.context import FSMContext
from aiogram.types import Message

from keyboards.main_menu import MENU_MUSIC
from services import music

router = Router()

# Что отвечаем, когда адрес выключен (`MUSIC_URL=""`). Молчать нельзя:
# человек, который сам нажал кнопку, прочитает тишину как поломку бота, а
# не как решение.
НЕТ_АДРЕСА = "🎧 Страница проекта сейчас недоступна. Загляни позже."


async def _показать(message: Message) -> None:
    """Одна дорога для кнопки и для команды."""
    if not await music.отправить(message):
        await message.answer(НЕТ_АДРЕСА)


@router.message(Command("music"))
async def cmd_music(message: Message) -> None:
    """Карточка по команде."""
    await _показать(message)


@router.message(F.text == MENU_MUSIC)
async def menu_music(message: Message, state: FSMContext) -> None:
    """Карточка по кнопке меню.

    Состояние чистим, как это делает «Профиль»: человек мог начать вводить
    шаги или правку роста и уйти сюда. Оставить его в недописанном ответе
    значило бы, что следующая его фраза молча уедет не туда.
    """
    await state.clear()
    await _показать(message)


__all__ = ["router"]
