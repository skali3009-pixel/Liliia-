"""Команда /music — вернуться к карточке SCALIA.

Карточка приходит один раз, в конце анкеты. Один раз — это правильно (второй
раз то же самое читается как реклама), но «один раз» без пути назад означает
«больше никогда»: человек, который в тот день торопился, не найдёт её уже
ничем. Команда и есть этот путь назад.

В меню Telegram её нет, и это то же решение, что у `/referral`: список
держится на десяти строках, и одиннадцатая вытеснила бы не «лишнюю» —
остальное либо ежедневное, либо обязано быть на виду по закону. Какую строку
заменить, выбирает Лилия.
"""

from __future__ import annotations

from aiogram import Router
from aiogram.filters import Command
from aiogram.types import Message

from services import music

router = Router()


@router.message(Command("music"))
async def cmd_music(message: Message) -> None:
    """Показать карточку ещё раз. Молчать здесь нельзя.

    Выключенный `MUSIC_URL` — это законное состояние, но человек, который
    сам набрал команду, ждёт ответа: молчание он прочитает как поломку бота.
    """
    if not await music.отправить(message):
        await message.answer("🎧 Страница проекта сейчас недоступна. "
                             "Загляни позже.")


__all__ = ["router"]
