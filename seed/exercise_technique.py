# Файлы показа движения: название упражнения → имя файла в
# `webapp/static/img/ex/`. Пусто, пока анимаций нет ни одной.
#
# Имена файлов выбираются здесь, а не выводятся из русского названия: иначе
# любая опечатка или переименование упражнения молча оставляли бы человека
# без картинки. Появится анимация — сюда добавляется строка, а сам файл
# скачивается тем же способом, что и остальные картинки AURA.
DEMO_IMAGES: dict[str, str] = {}


def demo_image(name: str) -> str | None:
    """Адрес анимации упражнения. None — пока её нет."""
    file = DEMO_IMAGES.get(name)
    return f"/static/img/ex/{file}" if file else None


def for_name(name: str) -> Technique | None:
    """Техника упражнения по его названию. None — пока не написана."""
    return TECHNIQUE.get(name)


