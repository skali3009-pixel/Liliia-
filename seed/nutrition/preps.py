PREPS: list[dict] = []


def _prep(code, name, components, *, instructions, source, portions=None, minutes=30,
          fridge="", freezer="", ideas=""):
    PREPS.append(dict(
        code=code, name=name, instructions=instructions, source=source,
        portions=portions, minutes=minutes, fridge_days=fridge, freezer_days=freezer,
        ideas=ideas, components=components,
    ))


def c(product, grams, raw=""):
    return dict(product_code=product, grams=float(grams), raw_amount=raw)


