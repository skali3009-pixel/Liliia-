"""Комбо без готовки: купил в магазине — сложил в миску — съел.

Зачем это есть. Дневник рушится не в те дни, когда человек не знает, что
полезно, а в те, когда готовить негде и некогда: дорога, работа, поздний
вечер. Обычно в такой день человек берёт что попало, а потом считает день
испорченным. Здесь у него есть план на этот случай.

Как это собрано. Это не рецепты Анастасии — звёздочки у них нет. Но собраны
они по её правилам и только из продуктов её же списков покупок:

- в каждом комбо есть источник белка — она требует его в каждом приёме;
- к белку идут овощи или фрукт, а не «просто белок»;
- жир — орехи, оливки, авокадо, фета: горсть, а не полпачки;
- порции взяты по её медианам (йогурт 150 г, орехи 20 г, тунец 100 г,
  хлеб 30 г за ломтик, фрукт — одна штука);
- ужин легче обеда, перекус — не тарелка.

Ничего не нужно варить, жарить и запекать. Максимум — открыть банку и
нарезать.
"""

from __future__ import annotations

from utils.measures import teaspoon

B, L, D, S = "breakfast", "lunch", "dinner", "snack"

STORE_DISHES: list[dict] = []


def _combo(code, name, meals, components, *, how, minutes=3, notes=""):
    STORE_DISHES.append(dict(
        code=code, name=name, meal_types=";".join(meals), portions=1,
        instructions=how, notes=notes, minutes=minutes,
        # Это не её рецепт: звёздочки быть не должно.
        author=False, source="", prep_codes="", estimated=False, no_cook=True,
        components=components,
    ))


def c(product, grams, raw="", optional=False, countable=False):
    return dict(product_code=product, grams=float(grams), raw_amount=raw,
                optional=optional, countable=countable)


