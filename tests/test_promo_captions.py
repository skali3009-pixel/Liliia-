"""Подписи промо-ролика: те же правила, что у техники упражнений и тура.

Промо видят люди, которые про AURA ещё ничего не знают, и первая
обещанная небылица стоит дороже всех остальных: её потом цитируют. Поэтому
здесь заперто то же, что и везде — ни обещаний результата, ни диагнозов,
одно предложение на подпись.
"""
import re
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
ПОДПИСИ_ФАЙЛ = КОРЕНЬ / "promo" / "captions.py"
ФИНАЛ = КОРЕНЬ / "promo" / "endcard.py"
МОНТАЖ = КОРЕНЬ / "promo" / "assemble.py"


def подписи() -> list[tuple[str, str, str]]:
    """Список подписей прямо из файла: ключ, надзаголовок, строка."""
    текст = ПОДПИСИ_ФАЙЛ.read_text(encoding="utf-8")
    кусок = текст.split("ПОДПИСИ = [", 1)[1].split("\n]", 1)[0]
    return re.findall(r'\("([^"]+)",\s*"([^"]+)",\s*"((?:[^"\\]|\\.)*)"\)', кусок)


def test_the_captions_promise_nothing_and_diagnose_nothing():
    """Ровно тот же запрет, что у техники и у тура."""
    все = " ".join(н + " " + с for _, н, с in подписи()).lower()
    for запрет in ("похуде", "вылеч", "гарантирова", "избавит", "сожжёт",
                   "результат за", "обязательно получится", "диагноз",
                   "безопасные дни", "минус 5 кг"):
        assert запрет not in все, запрет


def test_each_caption_is_one_sentence():
    """Ленту листают. Два предложения на карточке не читает никто."""
    for ключ, _, строка in подписи():
        живой = строка.replace("\\n", " ")
        # Точка в конце допустима, внутри — нет: это уже второе предложение.
        assert "." not in живой[:-1], (ключ, строка)
        assert len(живой) <= 90, (ключ, len(живой))


def test_the_scenes_and_the_captions_are_the_same_list():
    """Разъедутся — подпись будет говорить не о том, что на экране.

    Это уже случалось: «Одно дело — то, которое нужно сейчас» стояло на
    кадре с кольцом калорий, потому что сцену «Твой ход» не завели
    отдельно. Поймано глазами по контрольному листу, не тестом.
    """
    ключи_подписей = [к for к, _, _ in подписи()]
    кусок = МОНТАЖ.read_text(encoding="utf-8").split("СЦЕНЫ = [", 1)[1].split("\n]", 1)[0]
    ключи_сцен = re.findall(r'\("([^"]+)",\s*"[^"]+",', кусок)
    assert ключи_подписей == ключи_сцен, (ключи_подписей, ключи_сцен)


def test_the_bot_name_is_never_invented():
    """Промо с несуществующей ссылкой хуже, чем промо без ссылки.

    Имя бота в проекте пустое и узнаётся на ходу (`services/identity.py`),
    поэтому в финальную карточку оно только передаётся аргументом.
    """
    текст = ФИНАЛ.read_text(encoding="utf-8")
    разметка = текст.split("СТРАНИЦА = ", 1)[1].split('"""', 2)[1]
    # Смотрим только на то, что видно на карточке: в шапке живёт адрес
    # шрифтов, а в нём «собака» стоит законно (`wght@500`).
    тело = разметка.split("<body>", 1)[1]
    assert not re.search(r"@[A-Za-z_]", тело), "в карточке зашито имя бота"
    assert "t.me" not in тело
    # Пустая ручка — пустая строка, а не заглушка вроде «@aura_bot».
    assert "if ручка else \"\"" in текст
