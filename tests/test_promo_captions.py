"""Подписи промо-ролика: те же правила, что у техники упражнений и тура.

Промо видят люди, которые про AURA ещё ничего не знают, и первая
обещанная небылица стоит дороже всех остальных: её потом цитируют. Поэтому
здесь заперто то же, что и везде — ни обещаний результата, ни диагнозов,
одно предложение на подпись.
"""
import re
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
ПОДПИСИ_ФАЙЛ = КОРЕНЬ / "promo" / "captions.py"
ФИНАЛ = КОРЕНЬ / "promo" / "endcard.py"
МОНТАЖ = КОРЕНЬ / "promo" / "assemble.py"


def подписи() -> list[tuple[str, str, str]]:
    """Список подписей прямо из файла: ключ, надзаголовок, строка."""
    текст = ПОДПИСИ_ФАЙЛ.read_text(encoding="utf-8")
    кусок = текст.split("ПОДПИСИ = [", 1)[1].split("\n]", 1)[0]
    return re.findall(r'\("([^"]+)",\s*"([^"]+)",\s*"((?:[^"\\]|\\.)*)"\)', кусок)


def test_the_captions_promise_nothing_and_diagnose_nothing():
    """Ровно тот же запрет, что у техники и у тура."""
    все = " ".join(н + " " + с for _, н, с in подписи()).lower()
    for запрет in ("похуде", "вылеч", "гарантирова", "избавит", "сожжёт",
                   "результат за", "обязательно получится", "диагноз",
                   "безопасные дни", "минус 5 кг"):
        assert запрет not in все, запрет


def test_each_caption_is_one_sentence():
    """Ленту листают. Два предложения на карточке не читает никто."""
    for ключ, _, строка in подписи():
        живой = строка.replace("\\n", " ")
        # Точка в конце допустима, внутри — нет: это уже второе предложение.
        assert "." not in живой[:-1], (ключ, строка)
        assert len(живой) <= 90, (ключ, len(живой))


def test_the_scenes_and_the_captions_are_the_same_list():
    """Разъедутся — подпись будет говорить не о том, что на экране.

    Это уже случалось: «Одно дело — то, которое нужно сейчас» стояло на
    кадре с кольцом калорий, потому что сцену «Твой ход» не завели
    отдельно. Поймано глазами по контрольному листу, не тестом.
    """
    ключи_подписей = [к for к, _, _ in подписи()]
    кусок = МОНТАЖ.read_text(encoding="utf-8").split("СЦЕНЫ = [", 1)[1].split("\n]", 1)[0]
    ключи_сцен = re.findall(r'\("([^"]+)",\s*"[^"]+",', кусок)
    assert ключи_подписей == ключи_сцен, (ключи_подписей, ключи_сцен)


def test_the_bot_name_is_never_invented():
    """Промо с несуществующей ссылкой хуже, чем промо без ссылки.

    Имя бота в проекте пустое и узнаётся на ходу (`services/identity.py`),
    поэтому в финальную карточку оно только передаётся аргументом.
    """
    текст = ФИНАЛ.read_text(encoding="utf-8")
    разметка = текст.split("СТРАНИЦА = ", 1)[1].split('"""', 2)[1]
    # Смотрим только на то, что видно на карточке: в шапке живёт адрес
    # шрифтов, а в нём «собака» стоит законно (`wght@500`).
    тело = разметка.split("<body>", 1)[1]
    assert not re.search(r"@[A-Za-z_]", тело), "в карточке зашито имя бота"
    assert "t.me" not in тело
    # Пустая ручка — пустая строка, а не заглушка вроде «@aura_bot».
    assert "if ручка else \"\"" in текст


# --- Голос ----------------------------------------------------------------

ГОЛОС_ФАЙЛ = КОРЕНЬ / "promo" / "voice.py"


def реплики() -> dict[str, str]:
    текст = ГОЛОС_ФАЙЛ.read_text(encoding="utf-8")
    кусок = текст.split("РЕПЛИКИ: dict[str, str] = {", 1)[1].split("\n}", 1)[0]
    return dict(re.findall(r'"([a-z_]+)":\s*((?:"(?:[^"\\]|\\.)*"\s*)+)', кусок))


def test_the_voice_speaks_only_about_scenes_that_exist():
    """Реплика на сцене, которой нет, не прозвучит никогда — и молча."""
    кусок = МОНТАЖ.read_text(encoding="utf-8").split("СЦЕНЫ = [", 1)[1].split("\n]", 1)[0]
    сцены = set(re.findall(r'\("([^"]+)",\s*"[^"]+",', кусок))
    лишние = set(реплики()) - сцены
    assert not лишние, лишние


def test_the_voice_promises_nothing_and_diagnoses_nothing():
    """Те же правила, что у подписей, техники и тура."""
    все = " ".join(реплики().values()).lower()
    for запрет in ("похуде", "вылеч", "гарантирова", "избавит", "сожжёт",
                   "результат за", "обязательно получится", "диагноз"):
        assert запрет not in все, запрет


def test_the_voice_is_female():
    """Приложение обращается к женщине и говорит о её теле.

    Мужской голос здесь — не «тоже вариант», а чужой человек в разговоре,
    которого не звали.
    """
    текст = ГОЛОС_ФАЙЛ.read_text(encoding="utf-8")
    голоса = re.search(r"ГОЛОСА = \(([^)]*)\)", текст).group(1)
    выбранный = re.search(r'\nГОЛОС = "([a-z]+)"', текст).group(1)
    женские = {"anna", "arina", "elena", "irina", "tatiana", "victoria"}
    названные = set(re.findall(r'"([a-z]+)"', голоса))
    assert названные <= женские, названные - женские
    assert выбранный in названные, выбранный


def test_the_speaking_rate_is_not_read_as_a_percentage_offset():
    """У RHVoice шкала 0–100, где 100 — обычная речь, а не «плюс-минус».

    На этом я и попался: поставил «-8», ожидая «на восемь процентов
    медленнее», и получил речь вдвое быстрее обычной. Значение ниже нуля
    молча упирается в предел, и ошибку слышно только ухом — которого у
    меня нет.
    """
    текст = ГОЛОС_ФАЙЛ.read_text(encoding="utf-8")
    темп = re.search(r'ТЕМП = "(-?\d+)"', текст).group(1)
    assert 0 < int(темп) <= 100, темп


def test_the_video_carries_the_voice_without_losing_its_tail():
    """`-shortest` отмерял ролик по голосу, и последние секунды пропадали.

    Голос кончается раньше картинки, и вместе с ним уезжала финальная
    карточка — то есть единственное место, где написано имя бота.
    """
    монтаж = МОНТАЖ.read_text(encoding="utf-8")
    assert "-shortest" not in монтаж
    assert "apad" in монтаж and "atrim" in монтаж


def test_a_ready_made_recording_can_be_laid_out_by_scenes():
    """Чужой синтез приходит одной дорожкой, а фразы должны встать по кадрам.

    Синтез не метроном: одна и та же фраза от раза к разу выходит на
    полсекунды длиннее или короче, и подгонять паузы пересозданием
    бессмысленно. Поэтому готовая запись режется здесь — по тишине.
    """
    голос = ГОЛОС_ФАЙЛ.read_text(encoding="utf-8")
    assert "def разрезать(" in голос and "def переложить(" in голос
    assert "--from" in голос, "нет способа взять готовую запись"
    # Кусков речи должно найтись ровно столько, сколько реплик: молчаливая
    # склейка «нашли восемь вместо девяти» сдвинула бы весь ролик.
    кусок = голос.split("def разрезать(", 1)[1].split("\ndef ", 1)[0]
    assert "sys.exit" in кусок, "несовпадение числа кусков проходит молча"
