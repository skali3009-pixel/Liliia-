"""Оправа кадра 1080×1920 и финальная карточка.

Ролик снят в пропорции телефона (9:19,5), а лента ждёт 9:16. Растянуть
нельзя — поедут лица и кольца; обрезать сверху и снизу тоже нельзя — там
шапка и панель вкладок, то есть ровно то, что показываем. Поэтому экран
кладётся в кадр целиком, а свободное место сверху занимает подпись.
"""
import pathlib
from PIL import Image, ImageDraw, ImageFilter

ЗДЕСЬ = pathlib.Path(__file__).resolve().parent
СБОРКА = ЗДЕСЬ / "build"
СБОРКА.mkdir(exist_ok=True)
К_Ш, К_В = 1080, 1920
ЭКР_Ш, ЭКР_В = 720, 1558
ЭКР_X, ЭКР_Y = (К_Ш - ЭКР_Ш) // 2, 326
СКРУГЛ = 44

ПУСТОТА = (10, 9, 18)          # --void
ФИАЛКА = (139, 92, 246)        # --violet
ЛИЛОВЫЙ = (196, 181, 253)      # --lilac
ЗОЛОТО = (201, 169, 97)        # --gold


def свечение(холст):
    """Мягкий фиолетовый свет за экраном: без него кадр — плоское чёрное поле."""
    слой = Image.new("RGB", (К_Ш, К_В), ПУСТОТА)
    d = ImageDraw.Draw(слой)
    d.ellipse([ЭКР_X - 210, ЭКР_Y - 250, ЭКР_X + ЭКР_Ш + 210, ЭКР_Y + 620],
              fill=(46, 30, 92))
    d.ellipse([ЭКР_X + 40, ЭКР_Y + 900, ЭКР_X + ЭКР_Ш - 40, К_В + 200],
              fill=(28, 22, 58))
    слой = слой.filter(ImageFilter.GaussianBlur(190))
    return Image.blend(холст, слой, 0.85)


def оправа():
    """Фон (под экраном) и накладка (поверх): скругление и кромка."""
    фон = свечение(Image.new("RGB", (К_Ш, К_В), ПУСТОТА))

    # Накладка: прозрачное окно под экран, всё вокруг — цвет фона.
    верх = Image.new("RGBA", (К_Ш, К_В), (0, 0, 0, 0))
    d = ImageDraw.Draw(верх)
    # Сначала закрашиваем углы: рисуем весь кадр цветом фона…
    маска = Image.new("L", (К_Ш, К_В), 255)
    dm = ImageDraw.Draw(маска)
    dm.rounded_rectangle([ЭКР_X, ЭКР_Y, ЭКР_X + ЭКР_Ш, ЭКР_Y + ЭКР_В],
                         radius=СКРУГЛ, fill=0)
    цвет = фон.convert("RGBA")
    верх = Image.composite(цвет, Image.new("RGBA", (К_Ш, К_В), (0, 0, 0, 0)),
                           маска)
    # …и обводим окно тонкой кромкой, чтобы экран читался как экран.
    d = ImageDraw.Draw(верх)
    d.rounded_rectangle([ЭКР_X, ЭКР_Y, ЭКР_X + ЭКР_Ш, ЭКР_Y + ЭКР_В],
                        radius=СКРУГЛ, outline=(70, 56, 120, 255), width=2)
    return фон, верх


if __name__ == "__main__":
    фон, верх = оправа()
    фон.save(СБОРКА / "bg.png")
    верх.save(СБОРКА / "overlay.png")
    # Текста здесь нет нарочно: шрифты проекта приходят в woff2, а его PIL
    # не читает. Всё, где есть буквы, рисует браузер — теми же шрифтами,
    # что и само приложение.
    print("оправа готова:", фон.size, верх.size)
