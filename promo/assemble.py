"""Монтаж промо-ролика: обрезка, оправа, подписи, финал.

Пропорция. Экран телефона — 9:19,5, лента ждёт 9:16. Растянуть нельзя
(поедут кольца и лицо), обрезать сверху и снизу тоже нельзя — там шапка и
панель вкладок. Поэтому экран кладётся целиком, а свободное место сверху
занимает подпись: она и так нужна, потому что ленту смотрят без звука.
"""
import pathlib, subprocess, sys

ЗДЕСЬ = pathlib.Path(__file__).resolve().parent
СБОРКА = ЗДЕСЬ / "build"
СБОРКА.mkdir(exist_ok=True)
import imageio_ffmpeg
FF = imageio_ffmpeg.get_ffmpeg_exe()
СЫРЬЁ = (СБОРКА / "raw_path").read_text().strip()

# Метки из записи: имя → секунда в сыром файле.
МЕТКИ = dict((с.split("\t")[0], float(с.split("\t")[1]))
             for с in (СБОРКА / "marks.txt").read_text(encoding="utf-8").splitlines())
НАЧАЛО, КОНЕЦ = МЕТКИ["НАЧАЛО"], МЕТКИ["КОНЕЦ"]
ДЛИНА = КОНЕЦ - НАЧАЛО
ФИНАЛ = 3.4                     # сколько держим последнюю карточку
ВСЕГО = ДЛИНА + ФИНАЛ

ЭКР_Ш, ЭКР_В, ЭКР_X, ЭКР_Y = 720, 1558, 180, 326
ПОДП_X, ПОДП_Y = 40, 72
РАСТВОР = 0.35                  # плавность появления подписи


def окно(ключ_от, ключ_до):
    """Подпись живёт ровно свою сцену, с зазором на растворение."""
    от = МЕТКИ[ключ_от] - НАЧАЛО
    до = (МЕТКИ[ключ_до] - НАЧАЛО) if ключ_до else ДЛИНА
    return от + 0.25, до - 0.2


СЦЕНЫ = [
    ("start",  "НАЧАЛО",    "ход"),
    ("turn",   "ход",       "кольца"),
    ("rings",  "кольца",    "шаги"),
    ("steps",  "шаги",      "еда"),
    ("food",   "еда",       "спорт"),
    ("gym",    "спорт",     "проводник"),
    ("player", "проводник", "вес"),
    ("weight", "вес",       "календарь"),
    ("cycle",  "календарь", "мир"),
    ("world",  "мир",       None),
]


def main():
    вход = ["-i", СЫРЬЁ,
            "-loop", "1", "-i", str(СБОРКА / "bg.png"),
            "-loop", "1", "-i", str(СБОРКА / "overlay.png")]
    for ключ, _, _ in СЦЕНЫ:
        вход += ["-loop", "1", "-i", str(СБОРКА / "caps" / f"{ключ}.png")]
    вход += ["-loop", "1", "-i", str(СБОРКА / "endtext.png")]
    и_финал = 3 + len(СЦЕНЫ)

    цепь = [
        # Экран: вырезаем содержательную часть, держим последний кадр до
        # финала и уводим его в прозрачность — под ним остаётся свет оправы.
        f"[0:v]trim=start={НАЧАЛО}:end={КОНЕЦ},setpts=PTS-STARTPTS,fps=30,"
        f"scale={ЭКР_Ш}:{ЭКР_В}:flags=lanczos,format=yuva420p,"
        f"tpad=stop_mode=clone:stop_duration={ФИНАЛ + 0.5},"
        f"fade=t=out:st={ДЛИНА - 0.1}:d=0.8:alpha=1[app]",
        f"[1:v]scale=1080:1920,fps=30[bg]",
        "[bg][app]overlay=%d:%d[k0]" % (ЭКР_X, ЭКР_Y),
        "[k0][2:v]overlay=0:0[k1]",
    ]

    предыдущий = "k1"
    for i, (ключ, от_к, до_к) in enumerate(СЦЕНЫ):
        от, до = окно(от_к, до_к)
        вх = 3 + i
        цепь.append(
            f"[{вх}:v]format=rgba,"
            f"fade=t=in:st={от:.2f}:d={РАСТВОР}:alpha=1,"
            f"fade=t=out:st={до - РАСТВОР:.2f}:d={РАСТВОР}:alpha=1[p{i}]")
        след = f"s{i}"
        цепь.append(
            f"[{предыдущий}][p{i}]overlay={ПОДП_X}:{ПОДП_Y}:"
            f"enable='between(t,{от - 0.1:.2f},{до + 0.1:.2f})'[{след}]")
        предыдущий = след

    цепь.append(
        f"[{и_финал}:v]format=rgba,fade=t=in:st={ДЛИНА - 0.3:.2f}:d=0.8:alpha=1[fin]")
    цепь.append(f"[{предыдущий}][fin]overlay=0:0[почти]")
    # Въезд из темноты и уход в темноту — иначе ролик начинается рывком.
    цепь.append(f"[почти]fade=t=in:st=0:d=0.5,fade=t=out:st={ВСЕГО - 0.6:.2f}:d=0.6,"
                f"format=yuv420p[out]")

    выход = СБОРКА / "AURA_promo_1080x1920.mp4"
    команда = [FF, "-y", *вход, "-filter_complex", ";".join(цепь),
               "-map", "[out]", "-t", f"{ВСЕГО:.2f}",
               "-c:v", "libx264", "-preset", "slow", "-crf", "19",
               "-pix_fmt", "yuv420p", "-movflags", "+faststart",
               "-r", "30", str(выход)]
    print(f"длина содержания {ДЛИНА:.2f} с, с финалом {ВСЕГО:.2f} с")
    р = subprocess.run(команда, capture_output=True, text=True)
    if р.returncode:
        print(р.stderr[-3000:])
        sys.exit(1)
    print("готово:", выход, f"{выход.stat().st_size / 2**20:.1f} МБ")


main()
