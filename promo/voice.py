"""Озвучка промо-ролика: голос собирается по сценам, а не одним куском.

Почему по сценам. Одна длинная запись рано или поздно разъезжается с
картинкой: реплика про календарь звучит, когда на экране уже «Мой мир».
Поэтому каждая фраза синтезируется отдельно и кладётся ровно в начало
своей сцены — тех же сцен, что и подписи (`captions.py`, `assemble.py`).
Список один на всех троих, и это проверяется тестом.

Чем синтезируем. RHVoice из репозитория Ubuntu: русские женские голоса
(anna, arina, elena, irina, tatiana, victoria). Нейросетевые голоса
красивее, но забрать от них файл из рабочей сессии нельзя — прокси не
пускает ни к хранилищу HeyGen, ни к Higgsfield. RHVoice работает прямо
здесь, и это единственный путь, на котором голос вообще появляется.

**Голоса я не слышу.** Отсюда можно измерить длительность, темп и то, что
фраза уложилась в свою сцену; как она звучит — судит Лилия. Поэтому
`python promo/voice.py --samples` собирает образцы всех женских голосов
одним файлом: выбрать должна она.

    python promo/voice.py              # дорожка выбранным голосом
    python promo/voice.py --samples    # образцы всех голосов
"""
import array, math, pathlib, subprocess, sys, wave

import imageio_ffmpeg

ЗДЕСЬ = pathlib.Path(__file__).resolve().parent
СБОРКА = ЗДЕСЬ / "build"
СБОРКА.mkdir(exist_ok=True)
FF = imageio_ffmpeg.get_ffmpeg_exe()

# Женские голоса RHVoice. Мужские не берём: приложение обращается к
# женщине и говорит о её теле.
ГОЛОСА = ("anna", "arina", "elena", "irina", "tatiana", "victoria")
ГОЛОС = "elena"

# Чуть медленнее обычного: промо смотрят на ходу, и скороговорка в нём
# слышится суетой.
#
# Шкала у RHVoice не такая, как кажется по названию флага: это не «плюс-минус
# процентов», а 0–100, где 100 — обычная речь, а меньше — медленнее (замерено:
# 100 даёт те же 3,89 с, что и без флага, 80 — 4,86 с, 0 — 7,78 с). Значения
# ниже нуля молча упираются в предел и дают речь вдвое быстрее обычной —
# на этом я и попался, поставив «-8» и получив скороговорку.
ТЕМП = "90"

# Реплики. Ключ — сцена, с которой фраза начинается; говорить в каждой
# сцене не надо. Десять фраз на сорок семь секунд — это скороговорка без
# единой паузы, а промо смотрят на ходу. Поэтому фраза живёт до следующей
# озвученной сцены, а между ними — тишина, и это нормально.
#
# Текст не повторяет подпись слово в слово: на экране короткая строка, в
# голосе живая фраза. Правила те же, что у техники и тура: ни обещаний
# результата, ни диагнозов.
РЕПЛИКИ: dict[str, str] = {
    "start": "АУРА — приложение, которое не считает тебя ленивой.",
    "turn": "Оно называет одно дело. То, которое нужно прямо сейчас.",
    "rings": "И считает день целиком: еду, воду, шаги.",
    "food": "Не знаешь, что съесть — нажми «Реши за меня».",
    "gym": "Есть пятнадцать минут? Подберёт тренировку под это время.",
    "player": "И покажет движение. Прямо здесь, а не ссылкой на чужое видео.",
    "weight": "Вес, объёмы и фото по неделям.",
    "cycle": "Вес перед месячными выше не потому, что ты что-то сделала не так.",
    "world": "А закрытый день открывает кусочек мира.",
}


def метки() -> dict[str, float]:
    строки = (СБОРКА / "marks.txt").read_text(encoding="utf-8").splitlines()
    return {с.split("\t")[0]: float(с.split("\t")[1]) for с in строки}


def сцены() -> list[tuple[str, float, float]]:
    """(ключ, начало, конец) — в секундах от начала чистовика."""
    м = метки()
    нуль = м["НАЧАЛО"]
    порядок = [("start", "НАЧАЛО", "ход"), ("turn", "ход", "кольца"),
               ("rings", "кольца", "шаги"), ("steps", "шаги", "еда"),
               ("food", "еда", "спорт"), ("gym", "спорт", "проводник"),
               ("player", "проводник", "вес"), ("weight", "вес", "календарь"),
               ("cycle", "календарь", "мир"), ("world", "мир", "КОНЕЦ")]
    все = [(к, м[a] - нуль) for к, a, _ in порядок] + [("КОНЕЦ", м["КОНЕЦ"] - нуль)]
    озвученные = [(к, от) for к, от in все if к in РЕПЛИКИ or к == "КОНЕЦ"]
    # Фраза живёт до следующей озвученной сцены: в промежуточных сценах
    # голос молчит, и место под реплику от этого только прибавляется.
    return [(к, от, озвученные[i + 1][1])
            for i, (к, от) in enumerate(озвученные[:-1])]


def сказать(текст: str, файл: pathlib.Path, голос: str = ГОЛОС) -> float:
    """Синтезировать фразу. Вернуть длительность в секундах."""
    р = subprocess.run(["RHVoice-test", "-p", голос, "-r", ТЕМП, "-o", str(файл)],
                       input=текст, text=True, capture_output=True)
    if р.returncode or not файл.exists():
        sys.exit(f"RHVoice не справился: {р.stderr[-300:]}")
    with wave.open(str(файл)) as w:
        return w.getnframes() / w.getframerate()


def дорожка(голос: str = ГОЛОС) -> pathlib.Path:
    """Собрать одну звуковую дорожку под весь ролик."""
    куски = СБОРКА / "voice"
    куски.mkdir(exist_ok=True)
    части, входы, цепь = [], [], []
    тесно = []

    for i, (ключ, от, до) in enumerate(сцены()):
        файл = куски / f"{ключ}.wav"
        长 = сказать(РЕПЛИКИ[ключ], файл, голос)
        запас = (до - от) - 长
        пометка = "" if запас >= 0 else "  ← НЕ ВЛЕЗАЕТ"
        print(f"  {ключ:8} сцена {до - от:5.2f} с, речь {长:5.2f} с, "
              f"запас {запас:+5.2f}{пометка}")
        if запас < 0:
            тесно.append((ключ, -запас))
        части.append((файл, от))
        входы += ["-i", str(файл)]
        # Каждая реплика отодвигается на начало своей сцены.
        цепь.append(f"[{i}:a]adelay={int(от * 1000)}|{int(от * 1000)}[р{i}]")

    цепь.append("".join(f"[р{i}]" for i in range(len(части)))
                + f"amix=inputs={len(части)}:normalize=0,"
                # Мягкий предел: сложение дорожек не должно клиппировать,
                # даже если две реплики где-то наложатся.
                "alimiter=level_in=1:level_out=0.9,aformat=sample_rates=48000[out]")

    выход = СБОРКА / "voice.wav"
    к = [FF, "-y", "-v", "error", *входы, "-filter_complex", ";".join(цепь),
         "-map", "[out]", str(выход)]
    р = subprocess.run(к, capture_output=True, text=True)
    if р.returncode:
        sys.exit(р.stderr[-2000:])
    if тесно:
        print("\nРеплики длиннее своих сцен — их надо укоротить:")
        for ключ, сколько in тесно:
            print(f"   {ключ}: на {сколько:.2f} с")
    print(f"\nдорожка: {выход} ({выход.stat().st_size // 1024} КБ)")
    return выход


def разрезать(файл: pathlib.Path, сколько: int) -> list[tuple[float, float]]:
    """Найти в записи `сколько` кусков речи, разделённых тишиной.

    Нужно для готовой записи из чужого синтеза: там одна дорожка с паузами
    внутри, а фразы должны встать по кадрам поимённо.
    """
    сырой = subprocess.run([FF, "-v", "error", "-i", str(файл), "-ac", "1",
                            "-ar", "8000", "-f", "s16le", "-"],
                           capture_output=True).stdout
    d = array.array("h")
    d.frombytes(сырой[: len(сырой) // 2 * 2])
    окно = 8000 // 50                      # 20 мс
    громко = []
    for i in range(0, len(d) - окно, окно):
        кусок = d[i:i + окно]
        громко.append(math.sqrt(sum(х * х for х in кусок) / len(кусок)))
    порог = max(громко) * 0.03

    def нарезать(пауза: float) -> list[tuple[float, float]]:
        минимум = int(пауза * 50)
        куски, начало, тихо = [], None, 0
        for i, г in enumerate(громко):
            if г > порог:
                if начало is None:
                    начало = i
                тихо = 0
            elif начало is not None:
                тихо += 1
                if тихо >= минимум:
                    куски.append((начало / 50, (i - тихо) / 50))
                    начало = None
        if начало is not None:
            куски.append((начало / 50, len(громко) / 50))
        return куски

    # Порог тишины подбирается, а не назначается. Взять «полсекунды» на
    # глаз нельзя: внутри фраз синтез делает паузы почти такой же длины,
    # как между ними (замерено на живой записи: 0,98 с внутри фразы против
    # 1,17 с между фразами). Поэтому пробуем все пороги подряд и берём тот,
    # при котором кусков выходит ровно столько, сколько реплик, — а из
    # подошедших середину: она дальше всего от обеих границ.
    подошли = [ш / 100 for ш in range(30, 251, 5)
               if len(нарезать(ш / 100)) == сколько]
    if not подошли:
        сколько_вышло = {п: len(нарезать(п)) for п in (0.5, 1.0, 1.5, 2.0)}
        sys.exit(f"не нашёл порога, при котором кусков ровно {сколько}. "
                 f"При разных паузах выходит: {сколько_вышло}. "
                 "Значит, фразы в записи разделены не так, как в сценарии.")
    выбран = подошли[len(подошли) // 2]
    print(f"  порог тишины {выбран:.2f} с "
          f"(подошли от {подошли[0]:.2f} до {подошли[-1]:.2f})\n")
    return нарезать(выбран)


def переложить(файл: pathlib.Path) -> pathlib.Path:
    """Разложить готовую запись по сценам и собрать дорожку под ролик.

    Синтез — не метроном: одна и та же фраза от раза к разу выходит на
    полсекунды длиннее или короче, и подгонять паузы пересозданием
    бессмысленно. Проще разрезать готовое по тишине и поставить каждую
    фразу в начало её сцены.
    """
    сц = сцены()
    куски = разрезать(файл, len(сц))
    входы, цепь = [], []
    for i, ((ключ, от, до), (а, б)) in enumerate(zip(сц, куски)):
        запас = (до - от) - (б - а)
        пометка = "" if запас >= 0 else "  ← НЕ ВЛЕЗАЕТ"
        print(f"  {ключ:8} сцена {до - от:5.2f} с, речь {б - а:5.2f} с, "
              f"запас {запас:+5.2f}{пометка}")
        входы += ["-ss", f"{а:.3f}", "-to", f"{б + 0.15:.3f}", "-i", str(файл)]
        цепь.append(f"[{i}:a]adelay={int(от * 1000)}|{int(от * 1000)}[р{i}]")
    цепь.append("".join(f"[р{i}]" for i in range(len(сц)))
                + f"amix=inputs={len(сц)}:normalize=0,"
                "alimiter=level_in=1:level_out=0.9,aformat=sample_rates=48000[out]")
    выход = СБОРКА / "voice.wav"
    р = subprocess.run([FF, "-y", "-v", "error", *входы,
                        "-filter_complex", ";".join(цепь), "-map", "[out]",
                        str(выход)], capture_output=True, text=True)
    if р.returncode:
        sys.exit(р.stderr[-2000:])
    print(f"\nдорожка: {выход} ({выход.stat().st_size // 1024} КБ)")
    return выход

def образцы() -> pathlib.Path:
    """Одним файлом — все женские голоса на одной фразе.

    Слышать их я не могу: отсюда меряется только длительность и темп.
    Выбирает Лилия.
    """
    фраза = РЕПЛИКИ["cycle"]
    куски = СБОРКА / "samples"
    куски.mkdir(exist_ok=True)
    входы, цепь, номер = [], [], 0
    for голос in ГОЛОСА:
        имя = куски / f"{голос}.wav"
        подпись = куски / f"{голос}_имя.wav"
        сказать(f"Голос {голос}.", подпись, голос)
        сказать(фраза, имя, голос)
        входы += ["-i", str(подпись), "-i", str(имя)]
        цепь.append(f"[{номер}:a][{номер + 1}:a]")
        номер += 2
    цепь_текст = "".join(цепь) + f"concat=n={номер}:v=0:a=1[out]"
    выход = СБОРКА / "voice_samples.mp3"
    р = subprocess.run([FF, "-y", "-v", "error", *входы,
                        "-filter_complex", цепь_текст, "-map", "[out]",
                        "-b:a", "128k", str(выход)], capture_output=True, text=True)
    if р.returncode:
        sys.exit(р.stderr[-2000:])
    print(f"образцы шести голосов: {выход} ({выход.stat().st_size // 1024} КБ)")
    return выход


if __name__ == "__main__":
    if "--samples" in sys.argv:
        образцы()
    elif "--from" in sys.argv:
        # Готовая запись из чужого синтеза: режем по тишине и раскладываем.
        переложить(pathlib.Path(sys.argv[sys.argv.index("--from") + 1]))
    else:
        голос = sys.argv[1] if len(sys.argv) > 1 and not sys.argv[1].startswith("-") else ГОЛОС
        дорожка(голос)
