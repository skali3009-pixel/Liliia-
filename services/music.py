"""Карточка музыкального проекта SCALIA — отдельным сообщением.

Кнопка «Музыка SCALIA» жила под итогом анкеты, прицепленная к сообщению
«с чего начать». Так её не видели: следом уходят кружок, слайд, подарок за
приглашение и предложение дозаполнить анкету — пять сообщений, и кнопка
оказывается выше экрана раньше, чем человек до неё дотянется. Кнопка,
прицепленная к чужому сообщению, живёт ровно столько, сколько это сообщение
остаётся последним.

Поэтому теперь это своё сообщение и приходит оно последним. Отсюда два
следствия, и оба намеренные.

- **Карточка ничем не управляет.** Она не часть анкеты, не часть расчёта и
  не часть меню: не отправилась — не изменилось ничего. Сбой глотается, как
  у кружков и слайдов, по той же причине: человек пришёл заводить профиль,
  а не слушать музыку.
- **Ни подписки, ни счётчика, ни проверки перехода.** Нажатие на обычную
  URL-кнопку боту не приходит вовсе — показ кнопки не переход, а переход не
  прослушивание. Считать здесь нечего, и выдумывать себе цифру нельзя.

Отправляется один раз, в конце анкеты. Отдельной отметки «уже показывали»
нет и не нужно: `onboarding_completed` поднимается однажды, второго конца
анкеты у человека не бывает. Лишняя колонка в базе только добавила бы
способов разъехаться — тот же довод, что у кружков знакомства.

Вернуться к ней можно командой `/music`, сколько угодно раз.
"""

from __future__ import annotations

import logging

from aiogram.types import InlineKeyboardMarkup, Message
from aiogram.utils.keyboard import InlineKeyboardBuilder

import config

logger = logging.getLogger(__name__)

# Текст — от Лилии и о Лилии, поэтому он на «вы», хотя весь остальной бот
# говорит на «ты». Это не оплошность: здесь говорит не AURA, а человек,
# который её сделал, и про свой второй проект. Менять обращение — значит
# переписывать чужую речь о себе.
ТЕКСТ = (
    "🎧 Ещё один мой проект — SCALIA\n\n"
    "Я Лилия, автор AURA и музыкального проекта SCALIA. Здесь собраны мои "
    "песни и визуальные истории. Если захотите послушать — откройте "
    "страницу проекта."
)

КНОПКА = "Слушать SCALIA"


def клавиатура() -> InlineKeyboardMarkup | None:
    """Одна кнопка на страницу артиста. Нет адреса — нет и кнопки."""
    if not config.MUSIC_URL:
        return None
    builder = InlineKeyboardBuilder()
    builder.button(text=КНОПКА, url=config.MUSIC_URL)
    builder.adjust(1)
    return builder.as_markup()


async def отправить(message: Message) -> bool:
    """Показать карточку. Вернуть, дошла ли она.

    Ошибку глотаем нарочно и по тому же правилу, что у кружков: анкета
    обязана дойти до конца, чем бы ни кончилась отправка карточки.
    Выключенный адрес (`MUSIC_URL=""`) — не сбой, а решение: чужой сервис
    может пропасть, и убирается он одной настройкой.
    """
    доска = клавиатура()
    if доска is None:
        return False
    try:
        await message.answer(ТЕКСТ, reply_markup=доска,
                             disable_web_page_preview=True)
        return True
    except Exception:  # noqa: BLE001 — без карточки бот работает как работал
        logger.warning("Карточка SCALIA не отправилась — идём дальше",
                       exc_info=True)
        return False


__all__ = ["КНОПКА", "ТЕКСТ", "клавиатура", "отправить"]
