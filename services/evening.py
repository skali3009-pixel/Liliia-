"""Итоги дня — короткие и без попытки выжать ещё одно действие.

Соблазн здесь очевидный: вечером у человека открыто три задания, и можно
перечислить все три, добавить проценты, сравнить с прошлой неделей. Так
делать нельзя. Вечернее сообщение читают уставшими, и оно решает ровно
одну задачу: показать, что день уже почти сложился, и предложить — не
потребовать — закрыть одно небольшое дело.

Поэтому здесь два разных сообщения, а не одно с переменными.

Когда всё главное закрыто, бот говорит «на сегодня достаточно» и не даёт
никакой кнопки действия. Это не забытая возможность, а решение: человек,
который всё сделал, не должен получать вечером ещё одно предложение.

Состояния заданий берутся те же, что человек видит на экране, — из игрового
пересчёта. Придумывать здесь свои пороги «питание закрыто» значило бы
развести бота с приложением: на экране галочка есть, а в сообщении нет.
"""

from __future__ import annotations

from dataclasses import dataclass

# Вечер, но не ночь: ещё можно допить воду или пройтись, и это не поздний
# звонок. Час местный.
EVENING_HOUR = 21

# Сколько строк показываем. Полный список из восьми заданий — это отчёт,
# а отчёта вечером никто не ждёт.
MAX_LINES = 4

RESTING = (
    "🌙 На сегодня достаточно.\n\n"
    "Главные дела закрыты. Гепард отдыхает. И тебе можно.",
    "🌙 День сложился.\n\n"
    "Всё главное сделано. Дальше можно ничего не делать.",
    "🌙 Хватит на сегодня.\n\n"
    "Главное закрыто. Гепард уже спит, и это хорошая мысль.",
    "🌙 Всё, что нужно, сделано.\n\n"
    "Остаток вечера — просто вечер.",
    "🌙 День закрыт.\n\n"
    "Ничего не осталось. Можно выдохнуть.",
)

OPENING = (
    "🌙 День почти закончился.",
    "🌙 Вечер. Вот как сложился день.",
    "🌙 День подходит к концу.",
    "🌙 Почти всё на сегодня.",
    "🌙 День почти собран.",
)

CLOSING = (
    "Хочешь закрыть ещё одно маленькое дело?",
    "Осталось немного — закроем одно?",
    "Можно закрыть ещё одно. А можно и не закрывать.",
    "Одно небольшое дело — если есть силы.",
    "Закроем что-нибудь одно?",
)


@dataclass(frozen=True)
class Evening:
    """Вечернее сообщение и то, нужна ли под ним кнопка действия."""

    text: str
    resting: bool          # всё закрыто — предлагать больше нечего

    @property
    def target(self) -> str:
        """Куда ведёт кнопка. Пусто — кнопки действия не будет вовсе."""
        return "" if self.resting else "today"


def _line(quest: dict) -> str:
    mark = "✓" if quest.get("done") else "○"
    title = quest.get("title", "")
    hint = quest.get("hint") or ""
    if quest.get("done") or not hint:
        return f"{mark} {title}"
    return f"{mark} {title} — {hint}"


def render(quests: list[dict], *, seed: int = 0) -> Evening | None:
    """Итоги дня. None — если считать нечего и говорить не о чем."""
    if not quests:
        return None

    left = [quest for quest in quests if not quest.get("done")]
    if not left:
        return Evening(text=RESTING[seed % len(RESTING)], resting=True)

    done = [quest for quest in quests if quest.get("done")]
    # Ни одной галочки — и список превращается в перечень упрёков. Такому
    # человеку вечером полезнее обычная подсказка про одно дело, а не
    # четыре кружка подряд.
    if not done:
        return None

    # Сделанное сверху, оставшееся снизу: взгляд заканчивается на том, что
    # ещё можно закрыть, а не на списке заслуг.
    shown = done[:MAX_LINES - 1] + left[:MAX_LINES - len(done[:MAX_LINES - 1])]

    body = "\n".join(_line(quest) for quest in shown[:MAX_LINES])
    return Evening(
        text=(f"{OPENING[seed % len(OPENING)]}\n\n{body}\n\n"
              f"{CLOSING[seed % len(CLOSING)]}"),
        resting=False,
    )


__all__ = ["CLOSING", "EVENING_HOUR", "Evening", "MAX_LINES", "OPENING",
           "RESTING", "render"]
