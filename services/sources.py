"""Откуда человек пришёл: метка из ссылки, и только из закрытого списка.

В боте уже было поле `User.referral` — туда клался первый аргумент `/start`
как есть, любой строкой. Его не трогаем: на него можно посмотреть глазами,
и ломать то, что работает, ради отчёта незачем. Но для отчёта оно не годится
по двум причинам сразу. Первая: туда попадает и `friend_КОД`, и `team_КОД` —
служебные ссылки приглашений, а не источники рекламы. Вторая: туда попадает
что угодно, и в отчёте однажды оказалась бы произвольная строка, которую
никто не заводил.

Поэтому здесь список разрешённых меток закрыт, а всё остальное — не источник.

Три правила, которые легко перепутать.

- **`first_source` не меняется никогда.** Это ответ на вопрос «откуда он
  взялся», и второй запуск по другой ссылке его не переписывает.
- **`last_source` меняется только распознанной меткой.** Обычный `/start`
  без метки её не стирает: человек мог просто открыть бота из истории чатов,
  и это не значит, что источник забылся.
- **У заведённых раньше источник неизвестен, и выдумывать его нельзя.** Им
  ставится `existing_user`. Сегодняшняя метка у такого человека — не то,
  откуда он пришёл когда-то: он уже был. Считать его новым привлечением
  значит рисовать себе привлечение, которого не было.

**Метка называет площадку, а не ролик.** Так решено 22 сентября, и это не
упрощение, а отказ от обещания, которого ссылка не может сдержать. Отдельная
метка на каждое видео выглядит как способ сравнить ролики между собой — а на
деле человек смотрит ролик в ленте, уходит, возвращается через день и
запускает бота из шапки профиля. Метка честно отвечает «из инстаграма», и
выдавать её за «из ролика А1» значит считать то, чего не измеряли. Какой
ролик сработал — знает статистика самой площадки.
"""

from __future__ import annotations

# Площадки. Одна метка на соцсеть, и ссылка на бота у каждой одна.
PLATFORMS: tuple[str, ...] = (
    "instagram_profile",
    "threads_profile",
    "tiktok_profile",
    "youtube_profile",
    "vk_profile",
    "telegram_channel",
)

# Платная реклама в Telegram-каналах (первый тест, 29.10.2026). Здесь
# исключение из правила «метка называет площадку»: у платного размещения свой
# канал и своя цена, и без метки на каждый канал нельзя сказать, какое
# размещение окупилось. Список закрытый, как и весь остальной: новый канал —
# новая строка здесь, а не произвольный параметр в ссылке.
ADS: tuple[str, ...] = (
    "tg_pp_legko",
    "tg_recepty_pp",
    "tg_hudeem",
    "tg_iherb",
    "tg_bonrazione",
)

# Метки ролики-за-роликом, которые выдавались до 22.09.2026. Новых ссылок с
# ними не выпускаем, но распознавать обязаны: они уже разосланы, лежат в
# опубликованных постах и будут приходить ещё месяцами. Перестань их
# понимать — и человек по старой ссылке станет `direct_unknown`, то есть
# запись в базе окажется неправдой.
LEGACY: tuple[str, ...] = (
    "vk_a1_food",
    "vk_a2_move",
    "vk_a3_day",
    "vk_a4_progress",
    "vk_b1_bridge",
)

# Всё, что бот принимает за источник. Список закрытый: неизвестный параметр —
# не источник, и в отчёт он не попадает ни под каким видом.
MARKETING: tuple[str, ...] = PLATFORMS + ADS + LEGACY

# Запуск без распознанной метки у нового человека.
DIRECT = "direct_unknown"

# Человек, заведённый до того, как учёт появился.
EXISTING = "existing_user"

# Как метка называется в отчёте. Метка — это машинное слово из ссылки, и
# читать отчёт машинными словами владелице незачем.
НАЗВАНИЯ: dict[str, str] = {
    "instagram_profile": "Instagram",
    "threads_profile": "Threads",
    "tiktok_profile": "TikTok",
    "youtube_profile": "YouTube",
    "vk_profile": "VK",
    "telegram_channel": "Telegram-канал",
    "tg_pp_legko": "Реклама: ПП ЛЕГКО И ВКУСНО",
    "tg_recepty_pp": "Реклама: Рецепты пп",
    "tg_hudeem": "Реклама: ХУДЕЕМ БЕЗ ХИМИИ",
    "tg_iherb": "Реклама: Здоровое питание | iHerb",
    "tg_bonrazione": "Реклама: BonRazione",
    DIRECT: "Без метки (прямой заход)",
    EXISTING: "Были до учёта",
}

# Старые метки все до одной вели с VK. Это нужно, чтобы в отчёте сказать,
# сколько человек пришло с площадки всего, — но сказать отдельной строкой,
# не переписывая записанное.
ПЛОЩАДКА_LEGACY = "vk_profile"


def recognise(args: str | None) -> str | None:
    """Метка из аргумента `/start`, либо None.

    Служебные приставки приглашений (`friend_`, `team_`) сюда не попадают
    сами собой: их в списке нет. Перехватывать их нельзя — ими уже
    пользуются друзья и команды.
    """
    метка = (args or "").strip()
    return метка if метка in MARKETING else None


def apply(user, args: str | None, *, is_new: bool) -> str | None:
    """Проставить источники человеку. Возвращает распознанную метку.

    `is_new` — правда ли строку завели прямо сейчас. Ровно это и отличает
    «пришёл по ссылке» от «уже был и открыл бота ещё раз».
    """
    метка = recognise(args)

    if not user.first_source:
        # Меткой источник становится только у того, кого завели прямо сейчас.
        # У человека, который уже был, сегодняшняя ссылка — не то, откуда он
        # пришёл когда-то: записать её значит нарисовать себе привлечение,
        # которого не было. Сама метка при этом не теряется — она уходит в
        # `last_source` и учитывается отдельно.
        user.first_source = (метка or DIRECT) if is_new else EXISTING

    if метка:
        user.last_source = метка

    return метка


def свод(счёт: dict[str, int]) -> list[str]:
    """Строки отчёта по источникам. Считает, но ничего не переписывает.

    Записанное в базе остаётся как есть: старые метки роликов не
    склеиваются в `vk_profile` ни здесь, ни тем более в базе. Склейка
    сделала бы отчёт короче, а историю — ложной: пять разных меток
    превратились бы в одну, и отличить человека, пришедшего по старой
    ссылке, от пришедшего по новой стало бы нечем.

    Поэтому площадки идут строками, старые метки — отдельным блоком с
    пометкой, что их больше не выдают, а итог по VK называется явно: он
    один во всём отчёте требует сложения, и складывать его в уме владелице
    незачем.
    """
    if not счёт:
        return ["   пока никого"]

    строки: list[str] = []

    # Сначала площадки — то, чем пользуемся сейчас.
    площадки = [(м, с) for м, с in счёт.items() if м in PLATFORMS]
    for метка, сколько in sorted(площадки, key=lambda п: -п[1]):
        строки.append(f"   {НАЗВАНИЯ[метка]}: {сколько}")

    # Платная реклама — отдельным блоком: её цифры сравнивают между каналами
    # и с ценой размещения, и среди площадок они бы потерялись.
    реклама = [(м, с) for м, с in счёт.items() if м in ADS]
    if реклама:
        строки.append("   Платная реклама в каналах:")
        for метка, сколько in sorted(реклама, key=lambda п: -п[1]):
            строки.append(f"      {НАЗВАНИЯ[метка]}: {сколько}")

    # Потом то, что источником не является, но людей объясняет.
    for особая in (DIRECT, EXISTING):
        if счёт.get(особая):
            строки.append(f"   {НАЗВАНИЯ[особая]}: {счёт[особая]}")

    # И отдельно — старое. Не смешиваем: эти метки уже в базе, и делать вид,
    # что их не было, нельзя.
    старое = [(м, с) for м, с in счёт.items() if м in LEGACY]
    if старое:
        строки.append("   Старые метки роликов (больше не выдаются):")
        for метка, сколько in sorted(старое, key=lambda п: -п[1]):
            строки.append(f"      {метка}: {сколько}")
        всего_vk = счёт.get(ПЛОЩАДКА_LEGACY, 0) + sum(с for _, с in старое)
        строки.append(f"   Итого с VK (новая метка и старые): {всего_vk}")

    # Неизвестное в базе взяться может только руками — но если взялось,
    # молчать о нём нельзя: отчёт, который не сходится, хуже отчёта с
    # непонятной строкой.
    прочее = [(м, с) for м, с in счёт.items()
              if м not in PLATFORMS and м not in LEGACY and м not in ADS
              and м not in (DIRECT, EXISTING)]
    for метка, сколько in sorted(прочее, key=lambda п: -п[1]):
        строки.append(f"   {метка}: {сколько}")

    return строки


def ссылки() -> list[tuple[str, str]]:
    """Готовые ссылки на каждую площадку: (название, адрес).

    Адрес собирает `identity.start_link` — та же дверь, через которую
    выходят приглашения друзей и команд. Второй способ собрать ту же ссылку
    разошёлся бы с первым молча: ссылки продолжили бы выпускаться, переходы
    продолжили бы приниматься, а связь между ними однажды оборвалась бы. И
    имя бота бот узнаёт сам — вписывать его руками сюда незачем.

    Пока имя не известно, `start_link` возвращает пустую строку, и здесь
    она такой и остаётся: выдумывать адрес нельзя, ссылка в никуда хуже
    честного пробела.
    """
    from services.identity import start_link

    return [(НАЗВАНИЯ[метка], start_link(метка)) for метка in PLATFORMS]


def воронка_рекламы(пришло: dict[str, int], анкета: dict[str, int],
                    оплатили: dict[str, int]) -> list[str]:
    """Строки отчёта по платным размещениям: пришло → анкета → оплатили.

    Три числа — люди. Оплата считается по первому источнику человека, поэтому
    заплативший спустя неделю всё равно записан на канал, откуда пришёл.
    Каналы без единого перехода не показываются: пустая строка читается как
    «размещение вышло и не сработало», а это неизвестно.
    """
    строки = []
    for метка in ADS:
        сколько = пришло.get(метка, 0)
        if not сколько:
            continue
        строки.append(
            f"   {НАЗВАНИЯ[метка]}: пришло {сколько} · анкета "
            f"{анкета.get(метка, 0)} · оплатили {оплатили.get(метка, 0)}")
    return строки or ["   пока никого"]


def ссылки_рекламы() -> list[tuple[str, str]]:
    """Ссылки для платных размещений: (название канала, адрес).

    Собираются той же дверью, что и все остальные, — `identity.start_link`.
    """
    from services.identity import start_link

    return [(НАЗВАНИЯ[метка], start_link(метка)) for метка in ADS]


