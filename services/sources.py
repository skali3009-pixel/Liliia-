"""Откуда человек пришёл: метка из ссылки, и только из закрытого списка.

В боте уже было поле `User.referral` — туда клался первый аргумент `/start`
как есть, любой строкой. Его не трогаем: на него можно посмотреть глазами,
и ломать то, что работает, ради отчёта незачем. Но для отчёта оно не годится
по двум причинам сразу. Первая: туда попадает и `friend_КОД`, и `team_КОД` —
служебные ссылки приглашений, а не источники рекламы. Вторая: туда попадает
что угодно, и в отчёте однажды оказалась бы произвольная строка, которую
никто не заводил.

Поэтому здесь список разрешённых меток закрыт, а всё остальное — не источник.

Три правила, которые легко перепутать.

- **`first_source` не меняется никогда.** Это ответ на вопрос «откуда он
  взялся», и второй запуск по другой ссылке его не переписывает.
- **`last_source` меняется только распознанной меткой.** Обычный `/start`
  без метки её не стирает: человек мог просто открыть бота из истории чатов,
  и это не значит, что источник забылся.
- **У заведённых раньше источник неизвестен, и выдумывать его нельзя.** Им
  ставится `existing_user`. Сегодняшняя метка у такого человека — не то,
  откуда он пришёл когда-то: он уже был. Считать его новым привлечением
  значит рисовать себе привлечение, которого не было.
"""

from __future__ import annotations

# Метки продуктовых роликов. Список закрытый: неизвестный параметр —
# не источник, и в отчёт он не попадает ни под каким видом.
#
# B2 ведёт на музыку, а не в бота, — своей метки у него нет и не должно быть:
# ссылка на бота для него не заводилась.
MARKETING = (
    "vk_a1_food",
    "vk_a2_move",
    "vk_a3_day",
    "vk_a4_progress",
    "vk_b1_bridge",
)

# Запуск без распознанной метки у нового человека.
DIRECT = "direct_unknown"

# Человек, заведённый до того, как учёт появился.
EXISTING = "existing_user"


def recognise(args: str | None) -> str | None:
    """Метка из аргумента `/start`, либо None.

    Служебные приставки приглашений (`friend_`, `team_`) сюда не попадают
    сами собой: их в списке нет. Перехватывать их нельзя — ими уже
    пользуются друзья и команды.
    """
    метка = (args or "").strip()
    return метка if метка in MARKETING else None


def apply(user, args: str | None, *, is_new: bool) -> str | None:
    """Проставить источники человеку. Возвращает распознанную метку.

    `is_new` — правда ли строку завели прямо сейчас. Ровно это и отличает
    «пришёл по ссылке» от «уже был и открыл бота ещё раз».
    """
    метка = recognise(args)

    if not user.first_source:
        # Меткой источник становится только у того, кого завели прямо сейчас.
        # У человека, который уже был, сегодняшняя ссылка — не то, откуда он
        # пришёл когда-то: записать её значит нарисовать себе привлечение,
        # которого не было. Сама метка при этом не теряется — она уходит в
        # `last_source` и учитывается отдельно.
        user.first_source = (метка or DIRECT) if is_new else EXISTING

    if метка:
        user.last_source = метка

    return метка


__all__ = ["DIRECT", "EXISTING", "MARKETING", "apply", "recognise"]
