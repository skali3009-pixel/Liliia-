"""Аллергии: что человек написал — и какие продукты это исключает.

Аллергию пишут как попало: «орехи», «орех», «арахис», «на орехи», «яйца»,
«рыбу», «лактоза», «молочка», «орехи и мёд». Раньше каждое место подбора
понимало только своё: кубик сравнивал фразу целиком с меткой справочника
(«орехи» — да, «орех» и «арахис» — нет, и сам арахис предлагался человеку
с аллергией на арахис), подбор блюд искал слово целиком внутри названия
(«рыбу» не находилось в «рыба»), а необязательные ингредиенты — хлеб к супу
при глютене — не проверялись вовсе. Проверено на справочнике перебором:
из шестнадцати обычных формулировок семь пропускали сам аллерген.

Поэтому разбор один на всех, и ошибается он в безопасную сторону:

- известные слова сводятся к метке справочника по основе — «арахис»,
  «миндаль», «кешью» закрывают всю группу «орехи»: перекрёстные реакции и
  общие цеха здесь обычное дело, а лишний запрет стоит одного блюда,
  пропущенный — здоровья;
- незнакомое слово ищется по основе во всём, что известно о продукте:
  название, синонимы, метки («клубнику» найдёт «клубнику»);
- проверяется каждый ингредиент, включая необязательные.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

# Метка справочника → основы слов, по которым человек её называет.
GROUPS: dict[str, tuple[str, ...]] = {
    "орехи": ("орех", "арахис", "миндал", "кешью", "фундук", "фисташ", "пекан",
              "макадам", "кедров", "ореш"),
    "яйцо": ("яйц", "яиц", "яичн"),
    "молоко": ("молок", "молоч", "лактоз", "казеин", "сыр", "творог", "кефир",
               "йогурт", "сливк", "сметан"),
    "рыба": ("рыб",),
    "морепродукты": ("морепрод", "кревет", "кальмар", "мидии", "мидий", "краб",
                     "моллюск", "устриц"),
    "глютен": ("глютен", "пшениц", "клейковин", "целиак"),
    "кунжут": ("кунжут",),
    "соя": ("соя", "сои", "сою", "соев"),
    "мёд": ("мёд", "мед", "мёда", "меда"),
}

# Слова, которые окружают аллерген, но сами ничего не запрещают.
НЕ_АЛЛЕРГЕНЫ = {"аллергия", "аллергии", "аллергию", "на", "и", "или", "нет",
                "без", "не", "ем", "ест", "переношу", "непереносимость", "есть",
                "сильная", "лёгкая", "легкая", "немного", "все", "всё", "виды"}


@dataclass(frozen=True)
class Allergies:
    """Разобранная строка аллергий."""

    codes: frozenset[str]   # метки справочника: «орехи», «молоко»…
    stems: frozenset[str]   # основы незнакомых слов — ищутся в названии

    def __bool__(self) -> bool:
        return bool(self.codes or self.stems)

    def blocks(self, haystack: str, allergens: str = "", *, name: str | None = None) -> bool:
        """Запрещён ли продукт.

        `haystack` — название, синонимы и метки одной строкой; `allergens` —
        метки через «;»; `name` — само название. Группа по основам ищется в
        названии, а не в синонимах: у «Специй» среди синонимов «мускатный
        орех», и при аллергии на орехи пропадали бы тридцать блюд со щепоткой
        перца — проверено на справочнике.
        """
        text = (haystack or "").lower()
        marks = {part.strip() for part in (allergens or "").lower().split(";") if part}
        marks |= {word for word in re.split(r"[^а-яё]+", text) if word in GROUPS}
        if self.codes & marks:
            return True
        # Метка у продукта может быть не проставлена («Ореховая паста» без
        # «орехи») — тогда узнаём группу по основам в названии.
        title = (name if name is not None else text).lower()
        for code in self.codes:
            if any(stem in title for stem in GROUPS[code]):
                return True
        return any(stem in text for stem in self.stems)


def _stem(word: str) -> str:
    """Основа незнакомого слова: окончание падежа не должно мешать поиску."""
    return word[:-2] if len(word) > 5 else word


def parse(raw: str | None) -> Allergies:
    """Строка аллергий из анкеты → метки и основы."""
    codes: set[str] = set()
    stems: set[str] = set()
    for word in re.split(r"[^а-яёa-z]+", (raw or "").lower()):
        if len(word) < 3 or word in НЕ_АЛЛЕРГЕНЫ:
            continue
        found = {code for code, bases in GROUPS.items()
                 if any(word.startswith(base) for base in bases)}
        if found:
            codes |= found
        else:
            stems.add(_stem(word))
    return Allergies(frozenset(codes), frozenset(stems))


__all__ = ["Allergies", "GROUPS", "parse"]
