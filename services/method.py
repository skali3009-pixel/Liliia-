"""Метод Анастасии Явхуты, записанный правилами.

Её файлы — это не список блюд, а способ думать. Мы вынимаем из них принципы
и применяем ко всему, что бот показывает: и к её собственным рецептам, и к
блюдам, собранным сверх меню. Так подбор остаётся в её логике, а не
превращается в случайную выдачу из интернета.

Всё ниже выведено из её материалов:
- размеры порций — из граммовок в 42 карточках блюд;
- состав тарелки — из «базового принципа» боула: тёплый белок, овощи,
  зелень, соус;
- соусы — три формулы из меню-конструктора на 4 дня;
- «смузи не больше 200 мл», «в каждом приёме источник белка» — из заметок;
- «готовим один раз — едим несколько раз» — из гайда с заготовками.
"""

from __future__ import annotations

from dataclasses import dataclass

# --- Размеры порций ------------------------------------------------------
# Это не придуманные пороги: диапазоны посчитаны по её же 28 рецептам, по
# граммам на одну порцию. Если правило строже, чем её собственная еда, — это
# ошибка правила, а не рецепта.
#   белок 50–260 г (считая творог, йогурт и сыр — у неё это источник белка
#   на завтрак), крупа и крахмалистые 8–250 г (250 — картофель к индейке),
#   овощи 15–405 г, жир 2–40 г
PROTEIN_G = (50.0, 280.0)
GRAIN_G = (8.0, 270.0)
VEGETABLES_G = (15.0, 450.0)
ADDED_FAT_G = (2.0, 45.0)
# Ниже этого овощей в обеде и ужине не бывает ни в одном её блюде.
MIN_VEG_G_MAIN = 90.0
# Стакан смузи — прямая цитата из заметок.
SMOOTHIE_ML = 200.0

# --- Соусы: три формулы из меню-конструктора -----------------------------
SAUCES = {
    "универсальный": ("йогурт", "масло", "соль", "перец"),
    "яркий кислый": ("йогурт", "горчица", "лимонный сок", "мёд"),
    "ореховый": ("йогурт", "ореховая паста", "соевый соус", "лимон", "вода"),
}

# --- Правила по приёмам пищи ---------------------------------------------
# Ужин легче обеда — в её меню на ужин идут салаты и боулы, а не крупы с мясом.
DINNER_MAX_SHARE_OF_LUNCH = 1.0
# Перекус — это смузи или йогуртовый боул, а не полноценная тарелка.
SNACK_MAX_KCAL = 350.0

MIN_PROTEIN_SHARE = 0.15   # доля калорий из белка в приёме


@dataclass(frozen=True)
class Violation:
    """Нарушение принципа: что не так и почему это важно."""

    rule: str
    detail: str


def _role_grams(components: list[dict]) -> dict[str, float]:
    grams: dict[str, float] = {}
    for item in components:
        role = item.get("role", "прочее")
        grams[role] = grams.get(role, 0.0) + float(item.get("grams", 0))
    return grams


def check(*, meal_type: str, components: list[dict], kcal: float,
          protein_g: float) -> list[Violation]:
    """Проверить блюдо на соответствие методу.

    `components` — список словарей с ключами role и grams (роль берётся из
    справочника продуктов). Пустой ответ означает «всё в порядке».
    """
    problems: list[Violation] = []
    by_role = _role_grams(components)
    protein = by_role.get("белок", 0.0)
    grain = by_role.get("крупа", 0.0)
    vegetables = by_role.get("овощи", 0.0)
    # Добавленный жир — только масло. Орехи, авокадо и оливки жирные,
    # но это еда, а не долив в тарелку.
    added_fat = by_role.get("масло", 0.0)

    if meal_type == "snack":
        if kcal > SNACK_MAX_KCAL:
            problems.append(Violation("перекус", f"{kcal:.0f} ккал — это уже приём пищи"))
        return problems

    # Белок в каждом приёме: держит сытость и бережёт мышцы при снижении веса.
    if protein <= 0:
        problems.append(Violation("белок", "в приёме нет источника белка"))
    elif protein > PROTEIN_G[1]:
        problems.append(Violation(
            "порция белка", f"{protein:.0f} г — больше, чем в любом её рецепте"))

    # Долю белка спрашиваем с обеда и ужина: её завтраки — это творог с
    # фруктами и каша, там белка честно меньше, и это её осознанный выбор.
    if meal_type in ("lunch", "dinner") and kcal > 0 and \
            protein_g * 4 / kcal < MIN_PROTEIN_SHARE:
        problems.append(Violation("белок", "белка меньше 15% калорийности"))

    if meal_type in ("lunch", "dinner") and vegetables < MIN_VEG_G_MAIN:
        problems.append(Violation(
            "овощи", f"{vegetables:.0f} г овощей — половину тарелки не набрать"))

    if grain > GRAIN_G[1]:
        problems.append(Violation(
            "порция крупы", f"{grain:.0f} г крупы — больше, чем в любом её рецепте"))

    if added_fat > ADDED_FAT_G[1]:
        problems.append(Violation("жир", f"{added_fat:.0f} г масла — многовато"))

    return problems


def plate_hint(meal_type: str) -> str:
    """Короткая подсказка о тарелке — её же принцип, человеческими словами."""
    if meal_type == "breakfast":
        return "Завтрак: белок обязательно, крупа по желанию, овощи или фрукт."
    if meal_type == "snack":
        return "Перекус: стакан смузи не больше 200 мл или йогурт с фруктом."
    if meal_type == "dinner":
        return "Ужин легче обеда: белок и овощи, поменьше быстрых углеводов."
    return "Половина тарелки — овощи и зелень, четверть — белок, четверть — крупа."


