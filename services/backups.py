"""Резервные копии из чата: состояние и запуск по требованию.

Копии умеет делать `backup.sh` — он выгружает базу, пакует фотографии и
присылает архив владелице в Телеграм. Но запустить его можно было только из
консоли хостинга, а Лилия работает с айпада и просила «сделай всё
максимально сам». Консоль ради одной команды — это ровно то, чего быть не
должно; тот же довод, по которому кружки знакомства бот докачивает сам.

Отсюда два умения:

- **сказать, как обстоят дела** — когда была последняя копия и включено ли
  ночное расписание. Раньше это показывал только `bash status.sh`, то есть
  снова консоль;
- **сделать копию прямо сейчас** — тем же `backup.sh`, который работает по
  расписанию. Второй способ копировать разошёлся бы с первым в первый же
  день: одна копия оказалась бы без фотографий, и узнали бы об этом, когда
  она понадобится.

Обе работы блокирующие — они ходят в файловую систему и запускают чужие
процессы. Звать их надо из потока (`asyncio.to_thread`), а не из общего
цикла событий: в цикле это остановка всего бота. Свой цикл событий здесь
заводить нельзя — соединения с базой принадлежат тому, в котором живёт бот.
"""

from __future__ import annotations

import logging
import os
import subprocess
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

logger = logging.getLogger(__name__)

КОРЕНЬ = Path(__file__).resolve().parent.parent
ПАПКА = Path(os.getenv("BACKUP_DIR", "/root/nutrition-backups"))
ЮНИТ = "nutrition-bot-backup"

# Копия большой базы с фотографиями идёт минутами, а не секундами. Предел
# нужен, чтобы зависший pg_dump не держал поток вечно; десять минут с
# запасом покрывают всё, что бывает на таком сервере.
ПРЕДЕЛ_СЕК = 600


@dataclass(frozen=True)
class Состояние:
    """Что известно о копиях, не заходя в консоль."""

    последняя: datetime | None
    сколько: int
    мегабайты: int
    расписание: bool


def состояние() -> Состояние:
    """Когда была последняя копия и включено ли расписание. Блокирующая."""
    архивы = sorted(ПАПКА.glob("aura-*.tar.gz"),
                    key=lambda ф: ф.stat().st_mtime, reverse=True) \
        if ПАПКА.is_dir() else []

    последняя = мегабайты = None
    if архивы:
        последняя = datetime.fromtimestamp(архивы[0].stat().st_mtime)
        мегабайты = архивы[0].stat().st_size // 1024 // 1024

    return Состояние(последняя=последняя, сколько=len(архивы),
                     мегабайты=мегабайты or 0, расписание=_расписание())


def _расписание() -> bool:
    """Включён ли ночной таймер. Нет systemd — считаем, что нет."""
    try:
        готово = subprocess.run(
            ["systemctl", "is-enabled", f"{ЮНИТ}.timer"],
            capture_output=True, text=True, timeout=10)
    except (OSError, subprocess.SubprocessError):
        return False
    return готово.returncode == 0


def строки() -> list[str]:
    """Блок про копии для сводки. Блокирующая — звать из потока."""
    с = состояние()
    вышло = ["🗄 Резервные копии"]

    if с.последняя is None:
        вышло += ["   копий нет ни одной",
                  "   Сделать прямо сейчас: /backup"]
    else:
        вышло.append(f"   последняя: {с.последняя:%d.%m.%Y %H:%M} "
                     f"({с.мегабайты} МБ), всего на диске: {с.сколько}")

    вышло.append("   ночное расписание: "
                 + ("включено, копия приходит сюда файлом" if с.расписание
                    else "ВЫКЛЮЧЕНО — копии сами не делаются"))
    return вышло


def сделать() -> tuple[bool, str]:
    """Запустить `backup.sh`. Возвращает «получилось» и последние строки.

    Сам скрипт присылает готовый архив владелице в Телеграм и сообщает,
    если не смог, — поэтому здесь довольно вернуть исход и хвост вывода.
    """
    скрипт = КОРЕНЬ / "backup.sh"
    if not скрипт.exists():
        return False, "backup.sh не найден рядом с ботом"

    try:
        готово = subprocess.run(
            ["bash", str(скрипт), "--now"],
            capture_output=True, text=True, timeout=ПРЕДЕЛ_СЕК,
            cwd=str(КОРЕНЬ))
    except subprocess.TimeoutExpired:
        return False, f"копия не собралась за {ПРЕДЕЛ_СЕК // 60} минут"
    except OSError as ошибка:
        return False, f"не удалось запустить: {ошибка}"

    вывод = (готово.stdout or "") + (готово.stderr or "")
    хвост = "\n".join(вывод.strip().splitlines()[-6:])
    if готово.returncode != 0:
        logger.warning("Копия не сделалась: %s", хвост)
        return False, хвост or "скрипт завершился с ошибкой"
    return True, хвост


__all__ = ["ПАПКА", "ПРЕДЕЛ_СЕК", "Состояние", "сделать", "состояние", "строки"]
