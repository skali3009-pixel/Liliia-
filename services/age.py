def is_minor(user: User | None) -> bool:
    return bool(user is not None and user.age is not None and 0 < user.age < ADULT_AGE)


def adult_clause():
    """Условие выборки для рассылок: младшим 18 бот сам не пишет."""
    return or_(User.age.is_(None), User.age >= ADULT_AGE)


