"""AURA — для взрослых. Возраст входа — 18 лет.

Согласие в первом сообщении и оферта всегда говорили «старше 18», а анкета
принимала возраст от 10 — и 17-летнему профилю считалась взрослая норма
калорий, дефицит на снижение веса и взрослый «ориентир по весу» (запись
экрана 26.09). Показатели веса у детей и подростков читаются иначе, чем у
взрослых, поэтому переносить на них взрослые формулы молча нельзя, а своей
подростковой версии у AURA нет. Решение 27.09: единый вход с 18.

Для тех, кто уже завёл профиль младше 18, данные не удаляются: персональные
расчёты и советы выключаются, а свои записи можно выгрузить или удалить,
возраст — поправить, если он указан с ошибкой, и написать в поддержку.
"""

from __future__ import annotations

from sqlalchemy import or_

from models import User

ADULT_AGE = 18

# Новому человеку в анкете.
