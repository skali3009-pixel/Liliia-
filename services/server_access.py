"""Доступ Тимура к серверу — из чата, без консоли хостинга.

Настройку делает `grant-timur.sh`. Запустить его можно было только из
консоли, а серийная консоль у Лилии однажды просто перестала отвечать:
вставленное оставалось на экране и до сервера не доходило. Тот же довод,
что у `/backup`: страховка и обслуживание не должны зависеть от того,
откроется ли сегодня веб-консоль.

Второй способ выдавать доступ здесь не заводится — запускается тот же
скрипт, что и из консоли. Иначе два способа разошлись бы в первый же день:
один, например, забыл бы проверку правила sudo, и узнали бы об этом,
когда sudo перестал бы работать на всём сервере.

Вывод скрипта секретов не содержит (он так написан и проверен тестом), поэтому
его можно отдавать в чат как есть.
"""

from __future__ import annotations

import logging
import subprocess
from pathlib import Path

logger = logging.getLogger(__name__)

КОРЕНЬ = Path(__file__).resolve().parent.parent
СКРИПТ = КОРЕНЬ / "grant-timur.sh"

# Скрипт ничего не качает и не ставит: пользователь, ключ, четыре файла и
# правило sudo. Две минуты — с большим запасом; предел нужен, чтобы зависший
# дочерний процесс не держал поток бота вечно.
ПРЕДЕЛ_СЕК = 120

# Что можно попросить словами после команды. Ничего, кроме этих режимов,
# скрипту не передаётся: строка из чата в аргументы не попадает никогда.
РЕЖИМЫ = {"": [], "проверить": ["--check"], "убрать": ["--remove"]}


def режим(текст: str) -> list[str] | None:
    """Аргументы скрипта по тексту команды. None — режим не понят."""
    части = (текст or "").split(maxsplit=1)
    слово = части[1].strip().lower() if len(части) > 1 else ""
    return РЕЖИМЫ.get(слово)


def выполнить(аргументы: list[str]) -> tuple[bool, str]:
    """Запустить `grant-timur.sh`. Блокирующая — звать из потока.

    Возвращает «получилось» и вывод скрипта.
    """
    if not СКРИПТ.exists():
        return False, "grant-timur.sh не найден рядом с ботом — новая версия ещё не доехала"

    try:
        готово = subprocess.run(
            ["bash", str(СКРИПТ), *аргументы],
            capture_output=True, text=True, timeout=ПРЕДЕЛ_СЕК,
            cwd=str(КОРЕНЬ), stdin=subprocess.DEVNULL)
    except subprocess.TimeoutExpired:
        return False, f"скрипт не закончил за {ПРЕДЕЛ_СЕК} секунд"
    except OSError as ошибка:
        return False, f"не удалось запустить: {ошибка}"

    вывод = ((готово.stdout or "") + (готово.stderr or "")).strip()
    if готово.returncode != 0:
        logger.warning("Доступ Тимура не настроился: %s", вывод[-500:])
    return готово.returncode == 0, вывод or "скрипт ничего не вывел"


__all__ = ["ПРЕДЕЛ_СЕК", "РЕЖИМЫ", "СКРИПТ", "выполнить", "режим"]
