    "📱 Айфон — «Команды» (значок с двумя квадратами, уже стоит на телефоне)\n"
    "\n"
    "1. Открой «Команды» → внизу «Автоматизация» → «＋».\n"
    "2. Выбери «Время суток» → поставь 22:00 → «Ежедневно» → «Далее».\n"
    "3. «Новая пустая автоматизация» → «Добавить действие».\n"
    "4. Найди действие «Найти образцы состояния здоровья»:\n"
    "   • тип образцов — «Шаги»;\n"
    "   • добавь фильтр «Дата начала» → «сегодня»;\n"
    "   • внизу «Способ» → «Сумма».\n"
    "5. Добавь действие «Текст». Вставь в него свою ссылку, а сразу за ней "
    "подставь результат прошлого действия (появится синей плашкой).\n"
    "6. Добавь действие «Получить содержимое URL» и в поле адреса подставь "
