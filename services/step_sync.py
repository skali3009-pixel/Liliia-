# --- «Проверить подключение» ------------------------------------------------
#
# Кнопка нужна ровно потому, что настройка длинная: человек, собравший
# команду, должен узнать результат от нас, а не гадать до полуночи. И
# наоборот — если что-то не так, сказать это надо словами, а не молчанием.

# Дольше этого без единой присылки — связь считаем потерянной. Сутки плюс
# запас: ночная автоматизация приходит раз в день, и одна пропущенная ночь
# (телефон был выключен) ещё не повод пугать человека.
SILENT_HOURS = 30

# До этого часа ноль шагов — не поломка, а ночь: в «Здоровье» за новый день
# ещё нет записей. Ноль вообще законное число, и делать вид, что человек
# ошибся, нельзя.
EARLY_HOUR = 5


@dataclass(frozen=True)
class Check:
    """Что показать по кнопке «Проверить подключение»."""

    code: str
    title: str
    note: str
    ok: bool = False

    def to_dict(self) -> dict:
        return {"code": self.code, "title": self.title, "note": self.note,
                "ok": self.ok}


def ago(minutes: int) -> str:
    """«7 минут назад», «3 часа назад», «2 дня назад» — по-русски, с числом."""
    if minutes < 1:
        return "только что"
    if minutes < 60:
        return f"{minutes} {plural(minutes, 'минуту', 'минуты', 'минут')} назад"
    hours = minutes // 60
    if hours < 24:
        return f"{hours} {plural(hours, 'час', 'часа', 'часов')} назад"
    days = hours // 24
    return f"{days} {plural(days, 'день', 'дня', 'дней')} назад"


def plural(number: int, one: str, few: str, many: str) -> str:
    """Русское склонение после числа. Одиннадцать — «минут», а не «минута»."""
    tail, tens = number % 10, number % 100
    if 11 <= tens <= 14:
        return many
    if tail == 1:
        return one
    if 2 <= tail <= 4:
        return few
    return many


def check(*, minutes_since: int | None, today_steps: int, local_hour: int) -> Check:
    """Состояние связи с телефоном.

    `minutes_since` — сколько минут назад телефон присылал число; None —
    не присылал никогда.
    """
    if minutes_since is None:
        return Check(
            "never", "Шаги ещё не поступали",
            "Телефон ни разу не выходил на связь. Собери команду по "
            "инструкции и нажми в «Командах» ▶ — число придёт сразу.")

    when = ago(minutes_since)

    if minutes_since > SILENT_HOURS * 60:
        return Check(
            "silent", f"Телефон молчит: последний раз {when}",
            "Проверь в «Командах» → «Автоматизация», что запуск включён и "
            "стоит «Запускать немедленно», а не «Спрашивать».")

    if today_steps > 0:
        return Check(
            "ok", f"Подключено: {today_steps} "
                  f"{plural(today_steps, 'шаг', 'шага', 'шагов')}",
            f"Последнее обновление — {when}.", ok=True)

    if local_hour < EARLY_HOUR:
        return Check(
            "early", "Пока ноль — и это нормально",
            f"День только начался, в «Здоровье» ещё нет записей. Связь есть: "
            f"телефон присылал {when}.", ok=True)

    return Check(
        "zero", "Связь есть, но приходит ноль",
        "Если ты сегодня ходила, значит «Командам» не разрешили читать "
        "«Шаги». Открой команду, нажми на действие «Найти данные Здоровья» "
        "и разреши доступ.")


def as_text(cards: tuple[Card, ...] = CARDS, *, full: bool = True) -> str:
    """Те же карточки строкой — для чата, где карточек не бывает.

    `full=False` — короткий пересказ: у сообщения в Telegram потолок в 4096
    знаков, и полная инструкция в него не влезает. Обрезать нужно осознанно,
    а не узнавать об этом от человека, которому бот не ответил.
    """
    blocks = []
    for number, card in enumerate(cards, 1):
        lines = [f"{number}. {card.title}" + (f" — {card.lead}" if full else "")]
        lines += [f"   • {step}" for step in card.steps]
        if card.note and full:
            lines.append(f"   ({card.note})")
        blocks.append("\n".join(lines))
    return "\n\n".join(blocks)


