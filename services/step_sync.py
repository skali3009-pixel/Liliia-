SAFETY = (
    "Ссылка личная. По ней можно только записать шаги — прочитать что-либо о "
    "тебе нельзя. Если она куда-то утекла, поменяй её: старая перестанет "
    "работать сразу."
)

NO_SITE = (
    "Автоматическая присылка появится, когда у бота будет свой адрес в "
    "интернете. Пока вноси шаги кнопкой «👟 Шаги»."
)


def instructions(link: str) -> str:
    """Полная инструкция для чата: почему, ссылка, как настроить."""
    if not link:
        return NO_SITE
    return "\n\n".join([
        "⚡ Чтобы не вбивать шаги руками", WHY,
        f"Твоя ссылка:\n{link}", IPHONE, ANDROID, SAFETY,
    ])


__all__ = ["ANDROID", "IPHONE", "NO_SITE", "SAFETY", "WHY", "instructions",
           "link_for"]
