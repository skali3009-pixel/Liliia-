"""Автоматическая присылка шагов с телефона.

Почему без этого нельзя. Вбивать число руками каждый день не будет почти
никто — и тогда всё, что построено вокруг шагов, не работает: ни кольцо, ни
серия, ни команда, ни рейтинг.

Почему нельзя просто «поставить галочку и подключиться к Здоровью». Мини-
приложение внутри Telegram — это веб-страница. Ни iOS, ни Android не отдают
веб-странице данные здоровья: тут дело не в согласии человека, а в том, что
такого канала не существует вовсе. Читать «Здоровье» умеет только настоящее
приложение, установленное из магазина.

Обход: пусть телефон присылает шаги сам. На айфоне это делают «Команды» —
стандартное приложение Apple, которое умеет и брать шаги из «Здоровья», и
открывать ссылку по расписанию, без участия человека.

Устройство инструкции — главное, что здесь есть.

Первая версия описывала одну автоматизацию, внутри которой лежала вся
работа: взять шаги, сложить, отправить. Она не собралась ни у кого, кроме
автора. Две причины, и обе исправлены здесь.

1. Названия действий были неверные. «Найти образцы состояния здоровья» со
   «Способ → Сумма» — такого в проверенной версии iOS нет: данные берёт
   «Найти данные Здоровья», а сумму считает отдельное действие «Подсчитать
   статистику». Проверено на живом айфоне; ниже — только то, что дошло до
   сервера.

2. Вся работа лежала внутри автоматизации. Значит, вторая автоматизация —
   это вторая такая же сборка с нуля, третья — третья. Поэтому шаги
   отправлять чаще раза в сутки было практически невозможно.

Теперь сначала собирается одна именованная команда «AURA Sync», а любая
автоматизация — ночная, дневная, какая угодно — только запускает её. Новый
запуск стоит четырёх касаний вместо десяти минут, и «свежие шаги днём»
становятся реальными.

Текст один и тот же в чате и в приложении: карточки ниже — единственный
источник. Разошедшиеся инструкции в двух местах хуже, чем одна неудобная.
"""

