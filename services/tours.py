"""Какие подсказки человек уже видел.

Тур по вкладке нужен один раз — в первый заход. Раньше это помнил только
браузер телефона (`localStorage`), и у Лилии подсказка приходила при каждом
открытии вкладки: внутри Telegram страница живёт не как обычный сайт, и её
память переживает не всякое закрытие приложения.

Отсюда правило: **показанное — это про человека, а не про устройство.** Оно
хранится там же, где остальной профиль, и поэтому переживает и чистку кэша, и
новый телефон. Память браузера осталась рядом, но только как быстрый ответ:
она не даёт подсказке мигнуть, пока сервер ещё не ответил.

И отмечается тур показанным **в начале, а не в конце**. Дощёлкать до конца
человек не обязан: он закрывает приложение, ему звонят, он просто уходит
делать то, зачем зашёл. Прежний код ставил отметку только после последнего
шага или «Пропустить» — то есть у всех, кто ушёл раньше, тур начинался
заново, и так каждый раз. Вернуть его можно кнопкой в профиле.
"""

from __future__ import annotations

from sqlalchemy.ext.asyncio import AsyncSession

# Вкладки, у которых есть свой тур. Чужое сюда не пишем: строка в базе не
# резиновая, а список экранов закрытый.
SCREENS = ("today", "world", "gym", "cube", "progress")


def seen(user) -> list[str]:
    """Что уже показано — в порядке списка экранов, без повторов и мусора."""
    было = {часть for часть in (user.tours_seen or "").split(",") if часть}
    return [экран for экран in SCREENS if экран in было]


async def mark(session: AsyncSession, user, screen: str) -> bool:
    """Отметить тур показанным. False — если экран чужой или уже отмечен."""
    if screen not in SCREENS:
        return False

    было = seen(user)
    if screen in было:
        return False

    user.tours_seen = ",".join(sorted(set(было) | {screen}, key=SCREENS.index))
    await session.commit()
    return True


async def forget(session: AsyncSession, user) -> None:
    """Забыть всё — кнопка «Показать подсказки заново» в профиле."""
    user.tours_seen = ""
    await session.commit()


__all__ = ["SCREENS", "forget", "mark", "seen"]
