"""Слайды знакомства: три цветные карточки внутри анкеты.

Зачем. Анкета — девять вопросов подряд, и до приложения человек ещё не
дошёл: на экране только «укажи рост», а ради чего — не сказано нигде.
Отваливаются именно здесь. Слайд отвечает картинкой, потому что ещё одну
простыню текста в этом месте не читают.

Где именно и почему только там.

- **Что внутри** — сразу после согласия, перед первым вопросом. Это ответ
  на вопрос «а зачем мне отвечать».
- **Почему столько вопросов** — на середине, после целевого веса. Дальше
  идут самые скучные вопросы, и здесь человек чаще всего закрывает чат.
- **И в чате тоже** — после анкеты. Про команды иначе не узнают: они
  лежат за синей кнопкой, куда никто не смотрит, а приложение открывать
  готовы не все.

Больше нигде. Слайд после каждого вопроса — это не помощь, а мигание.

**Нет файла — нет и слайда.** Картинки лежат в репозитории, но если файл
потерялся или Telegram его не принял, анкета обязана дойти до конца:
человек пришёл заводить профиль, а не смотреть картинки.
"""

from __future__ import annotations

import logging
from pathlib import Path

from aiogram.types import FSInputFile, Message

logger = logging.getLogger(__name__)

SLIDES_DIR = Path(__file__).resolve().parent.parent / "media" / "slides"

# Имя файла → что на нём. Подпись здесь не для отправки: она держит рядом
# картинку и её смысл, иначе они разъезжаются молча.
SLIDES: dict[str, str] = {
    "what_is_inside": "Что внутри AURA — показывается сразу после согласия",
    "why_questions": "Почему столько вопросов — на середине анкеты",
    "in_chat_too": "Команды в чате — после анкеты",
}


def slide_path(name: str) -> Path | None:
    """Файл слайда, если он есть. Нет файла — None, и это не ошибка."""
    if name not in SLIDES:
        raise KeyError(f"неизвестный слайд: {name}")
    путь = SLIDES_DIR / f"{name}.png"
    return путь if путь.is_file() else None


async def send_slide(message: Message, name: str) -> bool:
    """Отправить слайд. Вернуть, отправился ли.

    Ошибку глотаем нарочно: если картинка не залилась, анкета всё равно
    обязана пойти дальше.
    """
    путь = slide_path(name)
    if путь is None:
        return False
    try:
        await message.answer_photo(FSInputFile(путь))
        return True
    except Exception:
        logger.warning("Слайд %s не отправился — идём дальше", name, exc_info=True)
        return False
