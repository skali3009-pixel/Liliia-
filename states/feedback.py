"""FSM-состояния разговора «что-то не так».

Два состояния и две стороны: человек пишет, что случилось, владелец пишет
ответ. Держим их порознь — иначе ответ владельца может уехать в ленту
сообщений как ещё одна жалоба.
"""

from aiogram.fsm.state import State, StatesGroup


class FeedbackStates(StatesGroup):
    # Человек рассказывает, что не так.
    writing = State()
    # Владелец пишет ответ конкретному человеку.
    answering = State()
