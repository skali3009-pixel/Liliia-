def _pick(options: tuple[str, ...], *, user_id: int, day: date) -> str:
    """Строка, одинаковая весь день для этого человека и разная у разных.

    Хэш, а не случайный выбор: иначе фраза менялась бы при каждом
    обновлении экрана. И не просто номер дня — тогда у всех подряд была бы
    одна и та же строка.
    """
    if not options:
        return ""
    seed = f"{user_id}:{day.isoformat()}".encode()
    index = int.from_bytes(blake2b(seed, digest_size=4).digest(), "big")
    return options[index % len(options)]


def pool_for(goal: str | None) -> tuple[str, ...]:
    """Из чего выбирается фраза: строки под цель плюс общие, про себя.

    Общие подмешиваются всегда — человеку важнее поддержка, чем ещё одно
    напоминание про калории.
    """
    return LINES.get(goal or "", DEFAULT_LINES) + CARE_LINES


def daily_line(*, goal: str | None, user_id: int, day: date) -> str:
    """Фраза дня под цель человека."""
    return _pick(pool_for(goal), user_id=user_id, day=day)


